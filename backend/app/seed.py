def seed_catalog(db: Session) -> int:
    """Добавляет отсутствующие демо-книги и возвращает число новых строк."""
    # AI: блокировка сериализует одновременный старт двух backend-контейнеров. Одной
    # проверки SELECT без неё недостаточно: оба процесса могли бы увидеть пустую таблицу.
    db.execute(text("SELECT pg_advisory_xact_lock(2026110101)"))
    titles = [book["title"] for book in DEMO_BOOKS]
    existing_titles = set(db.scalars(select(Book.title).where(Book.title.in_(titles))))
    missing = [Book(**book) for book in DEMO_BOOKS if book["title"] not in existing_titles]
    db.add_all(missing)
    db.commit()
    return len(missing)


def main() -> None:
    """Заполняет каталог из команды запуска контейнера."""
    with SessionLocal() as db:
        added = seed_catalog(db)
    print(f"Демонстрационный каталог: добавлено книг — {added}")


if __name__ == "__main__":
    main()
